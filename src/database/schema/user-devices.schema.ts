
import {
  pgEnum,
  pgTable,
  uuid,
  text,
  varchar,
  boolean,
  timestamp,
  index,
  uniqueIndex,
} from 'drizzle-orm/pg-core';

import { users } from './users.schema.js';

// ==========================================
// DEVICE PLATFORM ENUM
// ==========================================

export const devicePlatformEnum = pgEnum(
  'device_platform',
  [
    'ANDROID',
    'IOS',
  ],
);

// ==========================================
// USER DEVICES TABLE
// ==========================================

export const userDevices = pgTable(
  'user_devices',
  {
    id: uuid('id')
      .defaultRandom()
      .primaryKey(),

    // Device owner
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, {
        onDelete: 'cascade',
      }),

    // Unique ID generated by Flutter
    // and persisted for this app installation
    installationId: uuid('installation_id')
      .notNull(),

    // Firebase Cloud Messaging Token
    fcmToken: text('fcm_token')
      .notNull(),

    // Android or iOS
    platform: devicePlatformEnum('platform')
      .notNull(),

    // Optional device information
    deviceName: varchar('device_name', {
      length: 150,
    }),

    deviceModel: varchar('device_model', {
      length: 150,
    }),

    appVersion: varchar('app_version', {
      length: 50,
    }),

    // Device registration status
    isActive: boolean('is_active')
      .default(true)
      .notNull(),

    // Last successful registration/update
    lastSeenAt: timestamp('last_seen_at', {
      withTimezone: true,
    })
      .defaultNow()
      .notNull(),

    createdAt: timestamp('created_at', {
      withTimezone: true,
    })
      .defaultNow()
      .notNull(),

    updatedAt: timestamp('updated_at', {
      withTimezone: true,
    })
      .defaultNow()
      .notNull(),
  },
  (table) => [
    // One record per app installation
    uniqueIndex(
      'user_devices_installation_id_unique',
    ).on(table.installationId),

    // A Firebase token belongs to one installation
    uniqueIndex(
      'user_devices_fcm_token_unique',
    ).on(table.fcmToken),

    // Find all devices belonging to a user
    index(
      'user_devices_user_id_idx',
    ).on(table.userId),

    // Find active devices belonging to a user
    index(
      'user_devices_user_active_idx',
    ).on(
      table.userId,
      table.isActive,
    ),
  ],
);
