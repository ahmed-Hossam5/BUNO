/// Operations mode (references 91–94): what the team running the stations
/// sees. Stations and units are the same [mockStations] the app rents from;
/// temperatures, health, bay locks, connection, late rentals and pending
/// top-ups are mock data here. Nothing is sent anywhere.

/// A unit at or above this temperature (°C) is hot: the station locks its
/// bay on its own.
const opsHotTemperature = 42;

/// Battery health (percent of original capacity) below which a unit is
/// taken out of service.
const opsMinHealth = 70;

/// "من دقيقتين" / "2 min ago".
String opsMinutesAgo(int m) => tr(
      switch (m) {
        <= 1 => 'من دقيقة',
        2 => 'من دقيقتين',
        <= 10 => 'من $m دقايق',
        _ => 'من $m دقيقة',
      },
      '$m min ago',
    );

/// A temperature like `47°`, kept left-to-right as one run inside Arabic.
String opsDegrees(int t) => '\u2066$t°\u2069';

/// "خانات 1 و2 و5" / "bays 1, 2 and 5" (1-based).
String opsBayList(Iterable<int> bays) {
  final n = [for (final b in bays) '${b + 1}'];
  if (n.length == 1) return tr('خانة ${n.first}', 'bay ${n.first}');
  final ar = n.join(' و');
  final en = '${n.sublist(0, n.length - 1).join(', ')} and ${n.last}';
  return tr('خانات $ar', 'bays $en');
}

/// What the station reads off one bay: the unit's tag, charge, live
/// temperature and battery health, and whether the bay is locked (out of
/// service).
class OpsBay {
  const OpsBay({
    required this.index,
    required this.unit,
    required this.charge,
    required this.temperature,
    required this.health,
    required this.locked,
  });

  final int index;

  /// Null when the bay is empty (then [charge], [temperature] and [health]
  /// are null too).
  final UnitTag? unit;
  final int? charge;
  final int? temperature;
  final int? health;
  final bool locked;

  bool get empty => unit == null;
  bool get hot => (temperature ?? 0) >= opsHotTemperature;
  bool get worn => (health ?? 100) < opsMinHealth;
}

/// How a station is doing, as on /ops.
enum OpsStationStatus {
  offline(Tr('مش متصلة', 'Offline')),
  empty(Tr('فاضية', 'Empty')),
  full(Tr('مليانة', 'Full')),
  ok(Tr('تمام', 'OK'));

  const OpsStationStatus(this._label);

  final Tr _label;
  String get label => _label.text;
}

/// A rental past the reminder stage ([LateStage.reminder]).
class OpsLateRental {
  const OpsLateRental({required this.unitId, required this.station, required this.elapsed});

  final String unitId;

  /// Where it was picked up.
  final Station station;
  final Duration elapsed;

  LateStage get stage => LateStage.reachedAt(elapsed) ?? LateStage.reminder;
  Duration get left => LateStage.kept.at - elapsed;
}

/// A wallet top-up by transfer, waiting for the team to check the receipt.
class OpsPendingTopup {
  const OpsPendingTopup({required this.reference, required this.method, required this.waiting});

  /// Transfer reference number from the receipt.
  final String reference;
  final Tr method;
  final Duration waiting;
}

/// Task kinds, in the filter-chip order on /ops/tasks.
enum OpsTaskType {
  safety(Tr('أمان', 'Safety'), Tr('أمان', 'Safety')),
  transfer(Tr('نقل', 'Move'), Tr('نقل', 'Move')),
  maintenance(Tr('صيانة', 'Service'), Tr('صيانة', 'Service')),
  late(Tr('متأخر', 'Late'), Tr('متأخر', 'Late')),
  wallet(Tr('محفظة', 'Wallet'), Tr('شحن محفظة', 'Wallet top-up'));

  const OpsTaskType(this._chip, this._label);

  final Tr _chip;
  final Tr _label;

  /// Filter chip text.
  String get chip => _chip.text;

  /// Coloured line above a task's title.
  String get label => _label.text;
}

/// One thing for the team to do, generated by [opsTasks].
class OpsTask {
  const OpsTask({
    required this.id,
    required this.type,
    required this.urgency,
    required this.title,
    required this.detail,
    this.meta,
    this.station,
    this.target,
  });

  /// Stable across rebuilds, e.g. `hot:PB-0405`; [MockOps.markDone] uses it.
  final String id;
  final OpsTaskType type;

  /// Higher is more urgent; [opsTasks] sorts by it.
  final int urgency;
  final String title;
  final String detail;

  /// Small note at the end of the type line ("من دقيقتين", "~ 6 دقايق مشي").
  final String? meta;

  /// The station the task is at (for a transfer, where units come from).
  final Station? station;

  /// For a transfer: where the units go.
  final Station? target;
}

/// Seed readings: one hot unit (bay 3 of the first station) and two worn
/// ones, so every task type shows up with the stock [mockStations].
const _seedTemperature = {'PB-0405': 47};
const _seedHealth = {'PB-0388': 62, 'PB-0507': 58, 'PB-0615': 74};
const _defaultHealth = 93;
const _seedOffline = {'st-04'};

/// The ops mock state. Screens listen to [changes].
class MockOps {
  MockOps._();

  /// Bumped on every change (lock, task done, units moved).
  static final changes = ValueNotifier<int>(0);

  static final Map<String, int> _temperature = Map.of(_seedTemperature);
  static final Map<String, int> _health = Map.of(_seedHealth);
  static final Set<String> _offline = Set.of(_seedOffline);

  /// Bays locked or opened by the operator, as `stationId:bay`; any other
  /// bay is locked only while its unit is hot.
  static final Map<String, bool> _lockOverride = {};
  static final Set<String> _done = {};

  /// Mock counts for the dashboard.
  static const rentalsToday = 23;
  static const unitsOut = 7;

  /// How long ago the hot unit was detected (minutes).
  static const hotSinceMinutes = 2;

  /// Seconds since the stations last reported in.
  static const lastUpdateSeconds = 5;
  static const lastBeatSeconds = 3;

  static final List<OpsLateRental> lateRentals = [
    OpsLateRental(unitId: 'PB-0377', station: mockStations[0], elapsed: const Duration(hours: 23, minutes: 2)),
  ];

  static const pendingTopups = [
    OpsPendingTopup(reference: '448120', method: Tr('فودافون كاش', 'Vodafone Cash'), waiting: Duration(minutes: 12)),
    OpsPendingTopup(reference: '448157', method: Tr('فودافون كاش', 'Vodafone Cash'), waiting: Duration(minutes: 5)),
  ];

  /// Live temperature of [unit]: the seed reading, else its tag's.
  static int temperatureOf(UnitTag unit) => _temperature[unit.id] ?? unit.temperature;
  static int healthOf(UnitTag unit) => _health[unit.id] ?? _defaultHealth;

  static bool isOnline(Station s) => !_offline.contains(s.id);

  static String _key(Station s, int bay) => '${s.id}:$bay';

  static bool isLocked(Station s, int i) {
    final unit = s.units[i];
    return _lockOverride[_key(s, i)] ?? (unit != null && temperatureOf(unit) >= opsHotTemperature);
  }

  /// Locks bay [bay] at [s] (out of service) or opens it.
  static void setLocked(Station s, int bay, bool locked) {
    if (isLocked(s, bay) == locked) return;
    _lockOverride[_key(s, bay)] = locked;
    _notify();
  }

  static OpsBay bay(Station s, int i) {
    final unit = s.units[i];
    return OpsBay(
      index: i,
      unit: unit,
      charge: s.bays[i],
      temperature: unit == null ? null : temperatureOf(unit),
      health: unit == null ? null : healthOf(unit),
      locked: isLocked(s, i),
    );
  }

  static List<OpsBay> baysOf(Station s) => [for (var i = 0; i < s.bays.length; i++) bay(s, i)];

  static OpsStationStatus statusOf(Station s) {
    if (!isOnline(s)) return OpsStationStatus.offline;
    if (s.readyCount == 0) return OpsStationStatus.empty;
    if (s.emptyCount == 0) return OpsStationStatus.full;
    return OpsStationStatus.ok;
  }

  static bool isDone(String taskId) => _done.contains(taskId);

  static void markDone(String taskId) {
    if (_done.add(taskId)) _notify();
  }

  /// Call after units moved between bays so listeners rebuild.
  static void notifyMoved() => _notify();

  static void _notify() => changes.value++;

  static void reset() {
    _temperature
      ..clear()
      ..addAll(_seedTemperature);
    _health
      ..clear()
      ..addAll(_seedHealth);
    _offline
      ..clear()
      ..addAll(_seedOffline);
    _lockOverride.clear();
    _done.clear();
    rebalance.reset();
    _notify();
  }

  /// The one rebalance run /ops/rebalance reads.
  static final rebalance = OpsRebalance();
}

/// Fewest ready units; on a tie, the most empty bays.
Station _neediest(Iterable<Station> stations) => stations.reduce((a, b) {
      if (b.readyCount != a.readyCount) return b.readyCount < a.readyCount ? b : a;
      return b.emptyCount > a.emptyCount ? b : a;
    });

/// Most ready units.
Station _richest(Iterable<Station> stations) => stations.reduce((a, b) => b.readyCount > a.readyCount ? b : a);

/// How many units to move from [from] to [to]: half the gap in ready units
/// (rounded up), no more than [to] has room for.
int opsMoveCount(Station from, Station to) {
  final gap = from.readyCount - to.readyCount;
  if (gap <= 0) return 0;
  final half = (gap + 1) ~/ 2;
  return half < to.emptyCount ? half : to.emptyCount;
}

/// The [count] best-charged ready bays at [from].
List<int> opsMoveBays(Station from, int count) {
  final ready = [for (var i = 0; i < from.bays.length; i++) if (from.isReady(i)) i]
    ..sort((a, b) => from.bays[b]!.compareTo(from.bays[a]!));
  return (ready.take(count).toList()..sort());
}

/// The station that most needs units and the one with the most to spare
/// (online stations only, when there are at least two).
(Station from, Station to) opsSuggestedMove([List<Station>? stations]) {
  final all = stations ?? mockStations;
  final online = all.where(MockOps.isOnline).toList();
  final pool = online.length >= 2 ? online : all;
  final to = _neediest(pool);
  final from = _richest(pool.where((s) => s != to));
  return (from, to);
}

/// Every open task from the mock state, most urgent first. [stations]
/// defaults to [mockStations]; [late] and [topups] to [MockOps]'s lists.
List<OpsTask> opsTasks({
  List<Station>? stations,
  List<OpsLateRental>? late,
  List<OpsPendingTopup>? topups,
}) {
  final all = stations ?? mockStations;
  final online = all.where(MockOps.isOnline).toList();
  final tasks = <OpsTask>[];

  for (final s in online) {
    for (final b in MockOps.baysOf(s)) {
      final unit = b.unit;
      if (unit == null) continue;
      if (b.hot) {
        tasks.add(OpsTask(
          id: 'hot:${unit.id}',
          type: OpsTaskType.safety,
          urgency: 100 + b.temperature! - opsHotTemperature,
          title: tr('افحص خانة ${b.index + 1} في ${s.name}', 'Check bay ${b.index + 1} at ${s.name}'),
          detail: tr(
            'الوحدة ${unit.id} وصلت ${opsDegrees(b.temperature!)} والمحطة قفلتها. شيلها وافحصها.',
            'Unit ${unit.id} reached ${opsDegrees(b.temperature!)} and the station locked it. Take it out and check it.',
          ),
          meta: opsMinutesAgo(MockOps.hotSinceMinutes),
          station: s,
        ));
      }
      if (b.worn) {
        tasks.add(OpsTask(
          id: 'health:${unit.id}',
          type: OpsTaskType.maintenance,
          urgency: 40 + opsMinHealth - b.health!,
          title: tr('${unit.id} صحتها ${b.health}%', '${unit.id} at ${b.health}% health'),
          detail: tr(
            'تحت حد الـ$opsMinHealth%. طلّعها من الخدمة واستبدلها.',
            'Below the $opsMinHealth% limit. Take it out of service and replace it.',
          ),
          station: s,
        ));
      }
    }
  }

  // Empty stations get units from the richest one; full ones send units to
  // the one with the most room.
  if (online.length >= 2) {
    for (final to in online.where((s) => s.readyCount == 0)) {
      final from = _richest(online.where((s) => s != to));
      final t = _transfer(from, to, urgency: 80);
      if (t != null) tasks.add(t);
    }
    for (final from in online.where((s) => s.emptyCount == 0 && s.readyCount > 0)) {
      final to = online.where((s) => s != from).reduce((a, b) => b.emptyCount > a.emptyCount ? b : a);
      final t = _transfer(from, to, urgency: 75);
      if (t != null) tasks.add(t);
    }
  }

  final rentals = late ?? MockOps.lateRentals;
  for (final r in rentals) {
    final left = r.left.inMinutes;
    final alert = switch (r.stage) {
      LateStage.reminder => tr('الأول', 'first'),
      LateStage.warning => tr('التاني', 'second'),
      _ => tr('التالت', 'third'),
    };
    tasks.add(OpsTask(
      id: 'late:${r.unitId}',
      type: OpsTaskType.late,
      urgency: 50 + r.stage.index * 5,
      title: tr('وحدة متأخرة ${r.elapsed.inHours} ساعة', 'Unit ${r.elapsed.inHours} hours late'),
      detail: tr(
        '${r.unitId} مع مستخدم من امبارح. التطبيق بعتله التنبيه $alert.',
        '${r.unitId} has been out since yesterday. The app sent the $alert alert.',
      ),
      meta: left >= 55 ? tr('باقي ساعة', '1 hour left') : tr('باقي $left دقيقة', '$left min left'),
      station: r.station,
    ));
  }

  // One review task per payment method.
  final byMethod = <String, List<OpsPendingTopup>>{};
  for (final t in topups ?? MockOps.pendingTopups) {
    byMethod.putIfAbsent(t.method.en, () => []).add(t);
  }
  for (final group in byMethod.values) {
    final n = group.length;
    final oldest = group.map((t) => t.waiting.inMinutes).reduce((a, b) => a > b ? a : b);
    final method = group.first.method.text;
    tasks.add(OpsTask(
      id: 'topup:${group.first.method.en}',
      type: OpsTaskType.wallet,
      urgency: 60 + (oldest > 15 ? 15 : oldest),
      title: tr('راجع $n تحويل $method', 'Review $n $method transfers'),
      detail: tr('أقدم واحد من $oldest دقيقة.', 'Oldest one is $oldest min old.'),
      meta: tr('$n مستنيين', '$n waiting'),
    ));
  }

  tasks.removeWhere((t) => MockOps.isDone(t.id));
  tasks.sort((a, b) => b.urgency.compareTo(a.urgency));
  return tasks;
}

OpsTask? _transfer(Station from, Station to, {required int urgency}) {
  final n = opsMoveCount(from, to);
  if (n == 0) return null;
  final bays = opsMoveBays(from, n);
  final walk = (from.walkMinutes - to.walkMinutes).abs().clamp(1, 99);
  final why = to.readyCount == 0
      ? tr('${to.name} فاضية', '${to.name} is empty')
      : tr('${from.name} مليانة (0 فاضي)', '${from.name} is full (0 empty)');
  return OpsTask(
    id: 'move:${from.id}>${to.id}',
    type: OpsTaskType.transfer,
    urgency: urgency,
    title: tr('انقل $n وحدات لـ${to.name}', 'Move $n units to ${to.name}'),
    detail: tr('$why. خد من ${opsBayList(bays)} في ${from.name}.', '$why. Take ${opsBayList(bays)} at ${from.name}.'),
    meta: tr('~ $walk دقايق مشي', '~ $walk min walk'),
    station: from,
    target: to,
  );
}

/// Steps on /ops/rebalance.
enum RebalanceStep { open, verify, walk, drop }

/// A unit the operator took out of a bay: its tag and charge.
class CarriedUnit {
  const CarriedUnit(this.unit, this.charge);

  final UnitTag unit;
  final int charge;
}

/// Moving units from one station to another in 4 steps: the planned bays
/// open at [from]; the operator takes the units out (they leave [from] and
/// travel with the operator in [carried]); walks to [to]; drops them in
/// [to]'s empty bays.
class OpsRebalance extends ChangeNotifier {
  RebalanceStep _step = RebalanceStep.open;
  Station? _from;
  Station? _to;
  List<int> _bays = const [];
  final List<CarriedUnit> _carried = [];
  int _fromReady = 0;
  int _toReady = 0;

  bool get started => _from != null;
  RebalanceStep get step => _step;
  Station get from => _from!;
  Station get to => _to!;

  /// Bays at [from] to empty, 0-based.
  List<int> get bays => List.unmodifiable(_bays);

  /// Units with the operator, from [takeOut] until [dropAll].
  List<CarriedUnit> get carried => List.unmodifiable(_carried);

  /// Units on the move.
  int get count => _carried.isNotEmpty ? _carried.length : _bays.length;

  /// Ready units at [from] and [to] when the run started.
  int get fromReadyBefore => _fromReady;
  int get toReadyBefore => _toReady;

  /// Plans a run: [from] and [to] default to [opsSuggestedMove] (or the
  /// best match for the one given). Ignored while units are on the way.
  void start({Station? from, Station? to}) {
    if (_carried.isNotEmpty) return;
    Iterable<Station> others(Station s) => mockStations.where((o) => o != s);
    if (from == null && to == null) {
      (from, to) = opsSuggestedMove();
    } else if (from == null) {
      from = _richest(others(to!));
    } else {
      to ??= _neediest(others(from));
    }
    _from = from;
    _to = to;
    _bays = opsMoveBays(from, opsMoveCount(from, to));
    _fromReady = from.readyCount;
    _toReady = to.readyCount;
    _step = RebalanceStep.open;
    notifyListeners();
  }

  /// open → verify: the planned bays open one after another.
  void openBays() {
    if (_step != RebalanceStep.open || _bays.isEmpty) return;
    _step = RebalanceStep.verify;
    notifyListeners();
  }

  /// verify → walk: the units leave [from] and are with the operator.
  void takeOut() {
    if (_step != RebalanceStep.verify) return;
    for (final b in _bays) {
      _carried.add(CarriedUnit(from.units[b]!, from.bays[b]!));
      from.bays[b] = null;
      from.units[b] = null;
    }
    _step = RebalanceStep.walk;
    MockOps.notifyMoved();
    notifyListeners();
  }

  /// walk → drop.
  void arrive() {
    if (_step != RebalanceStep.walk) return;
    _step = RebalanceStep.drop;
    notifyListeners();
  }

  /// Puts every carried unit in [to]'s empty bays and ends the run.
  /// Returns how many were dropped.
  int dropAll() {
    if (_step != RebalanceStep.drop) return 0;
    var n = 0;
    for (final c in _carried) {
      final bay = to.firstEmptyBay;
      if (bay == null) break;
      to.bays[bay] = c.charge;
      to.units[bay] = c.unit;
      n++;
    }
    _carried.removeRange(0, n);
    if (_carried.isEmpty) MockOps.markDone('move:${from.id}>${to.id}');
    MockOps.notifyMoved();
    if (_carried.isEmpty) reset();
    return n;
  }

  void reset() {
    _step = RebalanceStep.open;
    _from = null;
    _to = null;
    _bays = const [];
    _carried.clear();
    notifyListeners();
  }
}
